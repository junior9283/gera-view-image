/** O valor do Flash é uma frase de partes separadas por vírgula. */
const FLASH = new Map(Object.entries({
  fired: "disparou",
  "not fired": "não disparou",
  "no return light detection function": "sem detecção de luz de retorno",
  "return light not detected": "luz de retorno não detectada",
  "return light detected": "luz de retorno detectada",
  forced: "forçado",
  suppressed: "desligado",
  auto: "automático",
  "no function present": "sem flash",
  "red-eye reduction": "redução de olhos vermelhos",
}));

const translated = (lang: string) => lang.startsWith("pt");

function flash(value: string): string {
  const parts = value.split(", ");
  if (!FLASH.has(parts[0])) return value;
  const text = parts.map((p) => FLASH.get(p) ?? p).join(", ");
  return text[0].toUpperCase() + text.slice(1);
}

export const fieldLabel = (label: string, lang: string): string => (translated(lang) ? (LABELS.get(label) ?? label) : label);

export function fieldValue(label: string, value: string, lang: string): string {
  if (!translated(lang)) return value;
  if (label === "Flash") return flash(value);
  return VALUES.get(label)?.get(value) ?? value;
}
